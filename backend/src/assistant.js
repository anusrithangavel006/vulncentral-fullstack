import { db } from './db.js';
const row = v => `${v.id} (${v.severity}${v.cvss ? ', CVSS ' + v.cvss : ''}${v.kev ? ', known exploited' : ''})`;

export async function answer(question) {
  const q = question.toLowerCase();
  const m = question.match(/CVE-\d{4}-\d+/i);
  const kev = db.prepare('SELECT * FROM vulns WHERE kev=1 ORDER BY cvss DESC').all();
  const crit = db.prepare("SELECT * FROM vulns WHERE severity='Critical' ORDER BY cvss DESC").all();
  let r;
  if (m) {
    const v = db.prepare('SELECT * FROM vulns WHERE id=?').get(m[0].toUpperCase());
    r = v ? { s: `${v.id}: ${v.title}. ${v.description}`, w: `${row(v)}.`, rel: v.id, ev: v.source, nx: v.mitigation || 'Check the vendor advisory.' }
          : { s: 'That CVE is not in the registry yet.', w: 'The registry only holds ingested records.', rel: '—', ev: '—', nx: 'Run an ingest or check NVD.' };
  } else if (q.includes('exploit')) r = { s: `${kev.length} registry records are flagged as known exploited.`, w: 'Exploitation in the wild raises urgency.', rel: kev.slice(0, 5).map(v => v.id).join(', '), ev: 'CISA KEV flag in registry', nx: 'Patch exploited items on exposed assets first.' };
  else if (q.includes('asset')) {
    const a = db.prepare("SELECT DISTINCT a.name FROM assets a JOIN asset_vulns av ON av.asset_id=a.id JOIN vulns v ON v.id=av.vuln_id WHERE v.severity='Critical'").all();
    r = { s: 'Assets matched to critical records: ' + (a.map(x => x.name).join(', ') || 'none') + '.', w: 'Matches are keyword-based; some need verification.', rel: 'Institutional Assets', ev: 'Asset inventory', nx: 'Verify versions on each asset.' };
  } else if (q.includes('patch') || q.includes('first')) r = { s: 'Start with critical, known-exploited records matched to important assets.', w: 'Severity plus exploitation plus asset importance drives priority.', rel: crit.filter(v => v.kev).slice(0, 4).map(v => v.id).join(', ') || '—', ev: 'Registry + task list', nx: 'Open the Remediation Center.' };
  else if (q.includes('difference')) r = { s: 'Severity (CVSS) rates the flaw; asset risk also weighs importance, exposure and fixes.', w: 'The same flaw matters more on a public portal than an isolated test box.', rel: '—', ev: 'General guidance', nx: 'Use both when prioritising.' };
  else r = { s: `${db.prepare('SELECT COUNT(*) c FROM vulns').get().c} records, ${kev.length} known exploited, ${crit.length} critical.`, w: 'Prioritise exploited and critical items.', rel: crit.slice(0, 4).map(v => v.id).join(', '), ev: 'Registry', nx: 'Review Priority Actions.' };
  r.lim = 'Rule-based answer from registry data.';

  // Optional LLM layer. Only active when ANTHROPIC_API_KEY is set. Not tested in the build environment.
  if (process.env.ANTHROPIC_API_KEY) {
    try {
      const ctx = JSON.stringify({ critical: crit.slice(0, 8).map(row), exploited: kev.slice(0, 8).map(row), draft: r });
      const res = await fetch('https://api.anthropic.com/v1/messages', {
        method: 'POST',
        headers: { 'content-type': 'application/json', 'x-api-key': process.env.ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01' },
        body: JSON.stringify({ model: process.env.ANTHROPIC_MODEL || 'claude-sonnet-5-5', max_tokens: 500, system: 'You explain vulnerability records to non-experts. Use ONLY the provided registry data. If unsure, say so. Do not invent CVE details.', messages: [{ role: 'user', content: `Question: ${question}\nRegistry data: ${ctx}` }] })
      });
      const j = await res.json();
      const text = j.content?.map(c => c.text || '').join('').trim();
      if (res.ok && text) { r.s = text; r.lim = 'Generated by an LLM from registry records; verify before acting.'; }
    } catch { /* fall back to the rule-based answer */ }
  }
  return r;
}
